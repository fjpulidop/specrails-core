import { tasksEditingFrozenArtifacts } from './artifact-contract.js'

/**
 * Review triage (capability `reviewTriage`): which reviewer issues the developer or fixer can act
 * on. A cheap reviewer sometimes rejects for something no correction round can change: a check the
 * host plan does not run (a device or simulator session, a manual pass), a lockfile the toolchain
 * regenerates, an edit to the frozen proposal, design or delta specs, or a criterion the person
 * withdrew in an answer. Such an issue is surfaced to the person as a note instead of burning a
 * correction round. Classification is deliberately conservative: an issue that also asks for work
 * the run can do (code, tests, another file) stays actionable, so a genuine rejection never weakens.
 */
export type NonActionableKind = 'host-only-check' | 'regenerated-lockfile' | 'frozen-artifact' | 'withdrawn-criterion'

export interface NonActionableIssue {
  /** The issue exactly as the reviewer wrote it (a string or an object). */
  issue: unknown
  text: string
  kind: NonActionableKind
  /** One sentence for the person: why the run cannot act on it. */
  reason: string
}

const REASONS: Record<NonActionableKind, string> = {
  'host-only-check': 'a check outside the host verification plan (a device, simulator or manual pass); the person makes it after delivery',
  'regenerated-lockfile': 'the lockfile is regenerated by the toolchain when the checks run; reverting or deleting it cannot stick',
  'frozen-artifact': 'proposal, design and delta specs are frozen before implementation; the run may only tick tasks',
  'withdrawn-criterion': 'the person withdrew this criterion in an answer during the run',
}

const LOCKFILE = /(?:^|[\s`'"(/])((?:[\w.-]+\/)*(?:Cargo\.lock|package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|go\.sum|poetry\.lock|uv\.lock|Pipfile\.lock|Gemfile\.lock|composer\.lock|Package\.resolved|Podfile\.lock|pubspec\.lock|mix\.lock|flake\.lock|gradle\.lockfile))\b/gi
const LOCKFILE_REQUEST = /\b(?:revert|reverts|reverting|delete|deletes|deleting|remove|removes|removing|restore|restoring|undo|discard|drop|exclude|unstage|reset|roll back|should not (?:be )?(?:change|modif|commit|includ|touch)|must not (?:be )?(?:change|modif|commit|includ|touch)|out[\s-]of[\s-]scope|unrelated|unexpected|unintended|unnecessary|churn|not (?:part of|in) the (?:plan|blast radius)|outside the blast radius)/i
/** A path-like token: something with a directory separator or a file extension. */
const PATH = /(?:^|[\s`'"(])((?:[\w@.-]+\/)+[\w@.-]+|[\w@-]+\.(?:[a-z]{1,6}))(?=$|[\s`'"),:;.])/gi
const HOST_ONLY = [
  /\b(?:real|physical|actual) (?:ios |android )?(?:device|phone|iphone|ipad|hardware|handset)s?\b/i,
  /\b(?:ios |iphone |ipad |android |xcode )?(?:simulator|emulator)s?\b/i,
  /\bmanual(?:ly)?[\s-]+(?:test(?:ing|ed|s)?|verif(?:y|ied|ication)|check(?:s|ed|ing)?|qa|pass|review|inspection|walk-?through|ui pass|smoke[\s-]test)\b/i,
  /\b(?:verify|verified|test|tested|check|checked|confirm|confirmed|inspect|inspected)\b[^.;\n]{0,60}?\bmanually\b/i,
  /\bby hand\b/i,
  /\bhost verification (?:did not|does not|doesn't|didn't|cannot|can't|never) (?:run|execute|build|launch)\b/i,
  /\b(?:xcodebuild|xcrun simctl|connectedAndroidTest|adb (?:install|shell)|docker push|npm publish|cargo publish|deploy(?:ed|ing)? to (?:production|staging|the app store|testflight))\b/i,
]
/** A directive to change code or tests: such a sentence is work the run can do. */
const WORK = /\b(?:add|adds|adding|write|writes|create|creates|fix|fixes|implement|implements|handle|handles|rename|refactor|extract|guard|validate|cover|covers|wire|export|import|assert|mock|stub|replace|move|call|return|throw|catch|use|log|clamp|escape|sanitize|parse|debounce|memoize|initiali[sz]e|update the (?:code|implementation|test|handler|function|component))\b/i
const WITHDRAWAL = /\b(?:drop|dropped|skip|skipped|remove|removed|withdraw|withdrawn|forget|ignore|ignored|leave out|left out|abandon|waive|waived|scrap|no longer (?:need|require|want)|(?:don't|do not|doesn't|does not) (?:need|require|want)|not (?:needed|required))\b\s*:?\s*(?:the\s+)?(?:requirement|criterion|criteria|constraint|guarantee)?s?\s*(?:of|for|about|that)?\s*([^.;!?\n]+)/gi
const FILLER = new Set(['the', 'and', 'that', 'this', 'for', 'with', 'all', 'any', 'requirement', 'requirements', 'criterion', 'criteria', 'constraint', 'guarantee', 'part', 'one', 'please', 'just', 'too', 'also', 'now', 'it', 'them', 'those', 'these'])

function issueText(issue: unknown): string {
  if (typeof issue === 'string') return issue
  if (issue && typeof issue === 'object' && !Array.isArray(issue)) {
    const record = issue as Record<string, unknown>
    const parts = ['title', 'message', 'description', 'issue', 'repair', 'fix', 'evidence', 'file', 'path'].map(key => record[key]).filter((value): value is string => typeof value === 'string')
    if (parts.length) return parts.join('. ')
  }
  return JSON.stringify(issue) ?? ''
}

const sentences = (text: string): string[] => text.split(/(?<=[.;!?])\s+|\n+/).map(sentence => sentence.trim()).filter(Boolean)
const paths = (text: string): string[] => [...text.matchAll(PATH)].map(match => match[1]!)

/** Every lockfile an issue names, and whether it asks for anything about another file. */
function lockfileOnly(text: string): boolean {
  const lockfiles = [...text.matchAll(LOCKFILE)].map(match => match[1]!.toLowerCase())
  if (!lockfiles.length || !LOCKFILE_REQUEST.test(text)) return false
  // Another file named next to the lockfile (a manifest, a source file) may be real scope creep.
  if (paths(text).some(path => !lockfiles.some(lockfile => path.toLowerCase().endsWith(lockfile.split('/').pop()!)))) return false
  return !sentences(text).some(sentence => !sentence.match(LOCKFILE) && WORK.test(sentence))
}

/** A host-only or frozen-artifact issue: every sentence is either the category itself (with no other work in it) or neutral prose. */
function onlyCategory(text: string, matches: (sentence: string) => RegExp | undefined): boolean {
  let matched = false
  for (const sentence of sentences(text)) {
    const pattern = matches(sentence)
    if (pattern) {
      matched = true
      if (WORK.test(sentence.replace(new RegExp(pattern.source, 'gi'), ' '))) return false
    } else if (WORK.test(sentence) || /\b(?:edit|edits|change|changes|modify|modifies|update|updates|remove|removes|delete|deletes|revert|reverts|ensure|ensures|make|makes)\b/i.test(sentence)) return false
  }
  return matched
}

/** Phrases the person withdrew in their answers ("drop O(1) and uniqueness" → ["O(1)", "uniqueness"]). */
export function withdrawnPhrases(answers: readonly string[]): string[] {
  const phrases: string[] = []
  for (const answer of answers) for (const match of answer.matchAll(WITHDRAWAL)) {
    for (const part of match[1]!.split(/,|\band\b|\bor\b|\bas well as\b/i)) {
      const phrase = part.replace(/[`"'“”]/g, '').trim()
      if (phrase.length >= 2 && phrase.length <= 80 && !FILLER.has(phrase.toLowerCase())) phrases.push(phrase)
    }
  }
  return [...new Set(phrases)]
}

function mentionsWithdrawn(text: string, phrases: readonly string[]): boolean {
  const lower = text.toLowerCase()
  return phrases.some(phrase => {
    const words = phrase.toLowerCase().match(/[a-z0-9]{3,}/g)?.filter(word => !FILLER.has(word)) ?? []
    // A symbolic phrase ("O(1)") must appear literally; a worded one needs all its words.
    return /^[\w\s-]+$/.test(phrase) && words.length ? words.every(word => new RegExp(`\\b${word}`, 'i').test(lower)) : lower.includes(phrase.toLowerCase())
  })
}

/** Split reviewer issues into the ones a correction round can act on and the ones only the person can. */
export function triageReviewIssues(issues: readonly unknown[], options: { change?: string; answers?: readonly string[] } = {}): { actionable: unknown[]; nonActionable: NonActionableIssue[] } {
  const withdrawn = withdrawnPhrases(options.answers ?? [])
  const actionable: unknown[] = [], nonActionable: NonActionableIssue[] = []
  for (const issue of issues) {
    const text = issueText(issue)
    const kind: NonActionableKind | undefined = lockfileOnly(text) ? 'regenerated-lockfile'
      : onlyCategory(text, sentence => tasksEditingFrozenArtifacts([{ text: sentence }], options.change ?? '').length ? /\b(?:proposal|design)\.md\b|openspec\/changes\/[\w-]+\/specs\/[\w/.-]*/ : undefined) ? 'frozen-artifact'
        : onlyCategory(text, sentence => HOST_ONLY.find(pattern => pattern.test(sentence))) ? 'host-only-check'
          : withdrawn.length && mentionsWithdrawn(text, withdrawn) ? 'withdrawn-criterion' : undefined
    if (kind) nonActionable.push({ issue, text, kind, reason: REASONS[kind] })
    else actionable.push(issue)
  }
  return { actionable, nonActionable }
}
